def overall_score(dimension_scores: dict) -> float:
    """按权重计算整体分（0-5，保留两位小数）。"""
    total = 0.0
    for dim in DIMENSIONS:
        total += dimension_scores.get(dim, 0.0) * WEIGHTS[dim]
    return round(total, 2)


def score_to_grade(score: float) -> str:
    """把 0-5 整体分映射为等级，用于人工可理解的判定。"""
    if score >= 4.5:
        return "优 (A)"
    if score >= 3.5:
        return "良 (B)"
    if score >= 2.5:
        return "中 (C)"
    if score >= 1.5:
        return "差 (D)"
    return "劣 (F)"


