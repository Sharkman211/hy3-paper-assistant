"""
rubric.py —— 论文阅读助手场景的评估维度定义（评估方法核心）

本文件定义了 6 个评估维度，每个维度给出 0-5 分的「可操作判定锚点」。
设计原则：
  1. 锚点以「可观察、可核对」的客观事实为准，避免使用
     「较好地满足要求」「基本符合」等无判定依据的模糊表述。
  2. 客观可程序化校验的维度（完整度/可追溯性/格式）用规则锚点；
     主观质量维度（事实准确性/术语正确性/可读性）用 LLM-as-judge 锚点，
     但同样给出可被不同评审者复现的判定条件。
  3. 每个维度给出权重，整体分 = Σ(维度分 × 权重)，范围 0-5。

章节对应任务书要求：覆盖 5 个以上关键维度
  —— 事实准确性、证据可追溯性、专业术语正确性、格式规范性、
     用户可理解性（可读性）、要点完整性，共 6 维。
"""

